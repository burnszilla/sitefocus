"""Shared helpers for sitefocus: safe reading of the crawl file, safe CSV
cells, trusted HTML markup, and private atomic file writes."""
import json
import os
import tempfile


def read_pages(path):
    """Crawl records from pages.jsonl, one per URL, the latest record winning
    (a resumed crawl appends retries). Damaged or partial lines are skipped."""
    out = {}
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                r = json.loads(line)
            except ValueError:
                continue
            if isinstance(r, dict) and r.get("url"):
                out[r["url"]] = r
    return list(out.values())


def repair_jsonl_tail(path):
    """If the last line of a JSONL file is incomplete or invalid (the process
    was killed mid-write), move it to <path>.damaged and truncate the file so
    appends start on a clean line. Returns True if anything was repaired."""
    if not os.path.exists(path) or os.path.getsize(path) == 0:
        return False
    with open(path, "rb") as f:
        data = f.read()
    complete = data.endswith(b"\n")
    body = data[:-1] if complete else data
    last = body.rsplit(b"\n", 1)[-1]
    try:
        json.loads(last)
        valid = True
    except ValueError:
        valid = False
    if valid and complete:
        return False
    if valid:  # a whole record that only lacks its newline
        with open(path, "ab") as f:
            f.write(b"\n")
        return True
    cut = len(body) - len(last)
    with open(path + ".damaged", "ab") as f:
        f.write(last + b"\n")
    with open(path, "r+b") as f:
        f.truncate(cut)
    return True


_FORMULA = ("=", "+", "-", "@", "\t", "\r")


def safe_cell(v):
    """Neutralise spreadsheet formula injection in text cells: a cell that
    starts with = + - @ or a control character gets a leading apostrophe.
    URLs and numbers are left alone."""
    if isinstance(v, str) and v and v[0] in _FORMULA and not v.startswith(("http://", "https://")):
        try:
            float(v)
            return v
        except ValueError:
            return "'" + v
    return v


class Markup(str):
    """HTML generated by sitefocus itself. Anything not wrapped in Markup is
    escaped before it is written into a report."""


def write_private(path, text):
    """Write a secret file atomically with 0600 permissions. Refuses to write
    through a symlink."""
    d = os.path.dirname(os.path.abspath(path))
    os.makedirs(d, exist_ok=True)
    try:
        os.chmod(d, 0o700)
    except OSError:
        pass
    if os.path.islink(path):
        raise SystemExit(f"{path} is a symlink; refusing to write credentials through it")
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".tmp-")
    try:
        os.fchmod(fd, 0o600) if hasattr(os, "fchmod") else None
        with os.fdopen(fd, "w") as f:
            f.write(text)
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.remove(tmp)
    if os.name == "posix" and (os.stat(path).st_mode & 0o077):
        raise SystemExit(f"could not make {path} private")
